class squarePattern {

    static void printsquare(int n) {
        for (int i = 1; i <= n; i++) {
            for (int j = 1; j <= n; j++) {
                System.out.println("nikhil");
            }
            System.out.println();
        }
    }

    public static void main(String[] args) {
        int size = 3; 
        printsquare(size);
    }
}
